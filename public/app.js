document.querySelector("#name-form").addEventListener("submit", async (event) => {
  event.preventDefault();
  const name = nameInput.value.trim();
  if (!name || !pendingEntry) return;
  const entry = pendingEntry;
  const submitButton = event.currentTarget.querySelector('button[type="submit"]');
  submitButton.disabled = true;
  nameError.classList.add("hidden");
  try {
    let room;
    if (entry.code) {
      room = await request(entry.kind === "group" ? "/api/groups/join" : "/api/join", {
        method: "POST",
        body: JSON.stringify({ code: entry.code, name }),
      });
    } else if (entry.kind === "single") {
      room = await request("/api/single", {
        method: "POST",
        body: JSON.stringify({ name, game: entry.game, difficulty: entry.difficulty }),
      });
    } else {
      room = await request(entry.kind === "group" ? "/api/groups" : "/api/rooms", {
        method: "POST",
        body: JSON.stringify({ name, game: entry.game, code: customCodeInput.value }),
      });
    }
    if (pendingEntry !== entry) return;
    pendingEntry = null;
    nameDialog.close();
    enterRoom(room);
  } catch (error) {
    if (pendingEntry !== entry) return;
    const errorKey = {
      "That room code is already in use.": "codeTaken",
      "Room code must contain 4 to 16 letters or numbers.": "invalidCode",
    }[error.message];
    nameError.textContent = errorKey ? t(errorKey) : error.message;
    nameError.classList.remove("hidden");
  } finally {
    submitButton.disabled = false;
  }
});

